import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto(process.env.LUNAQUEST_URL ?? 'http://127.0.0.1:5173/');
await page.waitForFunction(() => window.__lunaquestGame?.scene?.getScene('MoonBaseScene')?.sys?.isActive());
const state = () => page.evaluate(() => window.__lunaquestStore.getState());
const start = await state();
await page.waitForTimeout(2200);
let current = await state();
if (!(current.astronaut.health < start.astronaut.health && current.astronaut.health > start.astronaut.health - 1)) throw new Error('Normal gameplay HP did not decay slowly');
await page.getByRole('button', { name: 'Pause', exact: true }).click();
const paused = await state();
mkdirSync('artifacts', { recursive: true });
await page.screenshot({ path: 'artifacts/hp-food-paused.png', fullPage: true });
await page.waitForTimeout(1600);
current = await state();
if (!current.paused || current.astronaut.health !== paused.astronaut.health || current.astronaut.suitOxygen !== paused.astronaut.suitOxygen) throw new Error('HP or suit oxygen changed while paused');
await page.getByRole('button', { name: 'Resume Mission' }).click();
const resumed = await state();
await page.waitForTimeout(1200);
current = await state();
if (!(current.astronaut.health < resumed.astronaut.health)) throw new Error('HP did not resume decaying');
await page.evaluate(() => {
  const store = window.__lunaquestStore;
  const now = store.getState();
  store.dispatch({ type: 'LOAD_GAME', state: { ...now, weather: { ...now.weather, source: 'loading' } } });
});
const loading = await state();
await page.waitForTimeout(1200);
current = await state();
if (current.astronaut.health !== loading.astronaut.health || current.astronaut.suitOxygen !== loading.astronaut.suitOxygen) throw new Error('HP changed during loading');
await page.evaluate(() => {
  const store = window.__lunaquestStore;
  const now = store.getState();
  store.dispatch({ type: 'LOAD_GAME', state: { ...now, weather: { ...now.weather, source: 'demo' } } });
  window.__lunaquestGame.scene.getScene('MoonBaseScene').astronaut.setPosition(400, 226);
});
await page.waitForTimeout(260);
await page.keyboard.press('e');
await page.getByRole('button', { name: 'Enter Habitat' }).click();
const beforeEat = await state();
await page.getByRole('button', { name: /Eat Food/ }).click();
current = await state();
if (current.resources.food !== beforeEat.resources.food - 10 || current.astronaut.health < 99.8 || current.astronaut.health > 100) throw new Error('Eating did not spend stored food and restore HP');
await page.screenshot({ path: 'artifacts/hp-food-eaten.png', fullPage: true });
await page.evaluate(() => window.__lunaquestStore.dispatch({ type: 'UPDATE_ASTRONAUT', changes: { health: 0 } }));
await page.getByText('MISSION ENDED', { exact: true }).waitFor();
await page.waitForTimeout(800);
current = await state();
if (current.status !== 'defeat' || current.astronaut.health !== 0) throw new Error('HP changed after defeat');
if (errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`);
console.log('HP/food browser checks passed: slow decay, pause/resume, loading freeze, eating, and terminal freeze.');
await browser.close();
