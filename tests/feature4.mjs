import { chromium } from '@playwright/test';
import { mkdirSync } from 'node:fs';

const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
await page.goto(process.env.MOONBOUND_URL ?? 'http://127.0.0.1:5173/');
await page.waitForFunction(() => window.__moonboundGame?.scene?.getScene('MoonBaseScene')?.sys?.isActive());
mkdirSync('artifacts', { recursive: true });
const moveTo = async (x, y) => {
  await page.evaluate(([px, py]) => window.__moonboundGame.scene.getScene('MoonBaseScene').astronaut.setPosition(px, py), [x, y]);
  await page.waitForTimeout(260);
  await page.keyboard.press('e');
};
const state = () => page.evaluate(() => window.__moonboundStore.getState());
const close = () => page.getByRole('button', { name: 'Close building controls' }).click();
await moveTo(267, 316);
await page.getByRole('button', { name: /Plant Seeds/ }).click();
let current = await state();
if (!current.buildings.greenhouse.cropPlanted || current.resources.water !== 30 || current.resources.energy !== 71) throw new Error('Planting did not spend resources once');
const greenhouseTexture = () => page.evaluate(() => window.__moonboundGame.scene.getScene('MoonBaseScene').buildings.find((b) => b.entry.id === 'greenhouse').cropSprite.texture.key);
if (await greenhouseTexture() !== 'crop-seed') throw new Error('Seed pixel sprite is missing');
await page.screenshot({ path: 'artifacts/feature4-planted.png', fullPage: true });
await close();
await moveTo(400, 226);
await page.getByRole('button', { name: 'Enter Habitat' }).click();
await page.getByRole('button', { name: 'Advance Day' }).click();
current = await state();
if (current.buildings.greenhouse.cropGrowth !== 1 || current.lastDaySummary.energyProduced !== 16 || current.resources.energy !== 82) throw new Error('Growth and solar generation did not occur on day advance');
if (await greenhouseTexture() !== 'crop-sprout') throw new Error('Sprout animation stage is missing');
await page.waitForTimeout(750);
if (await greenhouseTexture() !== 'crop-ready') throw new Error('Ready crop pixel sprite is missing');
await page.getByRole('button', { name: 'Leave Habitat' }).click();
await close();
await moveTo(267, 316);
const beforeHarvestHealth = (await state()).astronaut.health;
await page.getByRole('button', { name: /Harvest Crop/ }).click();
current = await state();
if (current.resources.food !== 74 || current.resources.oxygen !== 78 || current.xp !== 5
  || current.astronaut.health > beforeHarvestHealth || current.astronaut.health < beforeHarvestHealth - 0.5) throw new Error('Harvest rewards or health rule failed');
await page.screenshot({ path: 'artifacts/feature4-harvest.png', fullPage: true });
await close();
await moveTo(538, 278);
if (!(await page.getByText('Next day: +16 energy in simplified daylight.').isVisible())) throw new Error('Solar production indicator missing');
await page.evaluate(() => {
  const store = window.__moonboundStore;
  const current = store.getState();
  store.dispatch({ type: 'LOAD_GAME', state: { ...current, buildings: { ...current.buildings, solar: { ...current.buildings.solar, condition: 'damaged' } } } });
});
await page.getByText('STATUS: DAMAGED').waitFor();
if (!(await page.getByText('Next day: +8 energy in simplified daylight.').isVisible())) throw new Error('Damaged solar indicator missing');
const beforeRepair = (await state()).resources.energy;
await page.getByRole('button', { name: /Repair solar/ }).click();
current = await state();
if (current.buildings.solar.condition !== 'good' || current.resources.energy !== beforeRepair - 10) throw new Error('Solar repair failed');
await page.screenshot({ path: 'artifacts/feature4-solar-repaired.png', fullPage: true });
await close();
await moveTo(608, 371);
const beforeShield = (await state()).resources.energy;
await page.getByRole('button', { name: /Activate Shield/ }).click();
current = await state();
if (!current.buildings.shield.active || current.resources.energy !== beforeShield - 8) throw new Error('Shield activation failed');
const ringVisible = () => page.evaluate(() => window.__moonboundGame.scene.getScene('MoonBaseScene').buildings.find((b) => b.entry.id === 'shield').shieldRing.visible);
if (!(await ringVisible())) throw new Error('Pixel shield ring is not visible');
await page.screenshot({ path: 'artifacts/feature4-shield.png', fullPage: true });
const protectedHealth = (await state()).astronaut.health;
await page.evaluate(() => window.__moonboundStore.dispatch({ type: 'APPLY_ENVIRONMENTAL_EXPOSURE', damage: 18 }));
if (Math.abs((await state()).astronaut.health - protectedHealth) > 0.5) throw new Error('Powered shield did not protect astronaut');
await page.evaluate(() => {
  const store = window.__moonboundStore;
  store.dispatch({ type: 'SPEND_RESOURCES', costs: { energy: store.getState().resources.energy } });
});
if (await ringVisible()) throw new Error('Shield ring stayed visible without power');
if ((await state()).buildings.shield.active) throw new Error('Shield did not switch off after losing power');
const exposedHealth = (await state()).astronaut.health;
await page.evaluate(() => window.__moonboundStore.dispatch({ type: 'APPLY_ENVIRONMENTAL_EXPOSURE', damage: 18 }));
if (Math.abs((await state()).astronaut.health - (exposedHealth - 18)) > 0.5) throw new Error('Unpowered shield incorrectly protected astronaut');
if (errors.length) throw new Error(`Browser errors: ${errors.join(' | ')}`);
console.log('Feature 4 browser checks passed: seed/sprout/ready, harvest, solar yield/repair, shield protection and power failure.');
await browser.close();
